def b(id_, term, pattern, type_, section, fix, *, scope="공통", exempt=None, exempt_if_all=None,
      law_id=None, note=None):
    rule = {
        "id": id_, "term": term, "pattern": pattern, "level": 2, "type": type_, "scope": scope,
        "basis_id": section if section.startswith(("LAW_", "NOTICE_", "GUIDE_")) else G + section,
        "law_id": law_id or LAW_BY_TYPE[type_], "fix_hint": fix,
    }
    if exempt:
        rule["exempt_functional"] = exempt
    if exempt_if_all:
        rule["exempt_if_all"] = exempt_if_all
    if note:
        rule["note"] = note
    return rule


