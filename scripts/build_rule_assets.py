def _validate() -> None:
    ids = set()
    for rule in banned + substantiation + comparison + exaggeration:
        re.compile(rule["pattern"], re.IGNORECASE)
        assert rule["type"] in VIOLATION_TYPES, rule["id"]
        assert rule["id"] not in ids, rule["id"]
        ids.add(rule["id"])
        for key in ("basis_id", "law_id"):
            assert re.match(r"^(LAW|GUIDE|NOTICE)_", rule[key]), (rule["id"], key)
            assert "COSMETIC" not in rule[key], (rule["id"], key)


def _write(name: str, data) -> None:
    (ASSETS / name).write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


