PLACEHOLDER_NAMES = {"", "나의 화장품"}


def _display_name(product: dict[str, Any]) -> str:
    """빠른 생성의 임시 이름('나의 화장품')을 모델이 제품명처럼 문구에 쓰지 않게 한다."""
    name = str(product.get("name") or "").strip()
    return "미정 (문구에 제품명을 쓰지 말고 제품 유형으로 부른다)" if name in PLACEHOLDER_NAMES else name


def product_fact_lines(product: dict[str, Any]) -> list[str]:
    """[제품] 블록에 넣을 제품 사실 줄. 입력된 칸만 넣고, 하나도 없으면 미확인이라고 적는다."""
    rows = [f"- {label}: {str(product.get(key)).strip()}" for key, label in PRODUCT_FACTS if str(product.get(key) or "").strip()]
    return rows or ["- 제품 사실(질감·향·용기 등): 미확인 (지어내지 말 것)"]


def build_generation_prompt(
    *,
    instruction: str,
    product: dict[str, Any],
    channel: str,
    tone: str,
    length: str,
    keywords: list[str],
    evidence_text: str,
    retry_note: str | None = None,
    claim_menu: str = "",
    product_description: str = "",
    reference_copy: str = "",
    knowledge: str = "",
    market_reference_text: str = "",
    ingredient_reference_text: str = "",
) -> str:
    evidences = product.get("owned_evidence") or []
    evidence_rows = []
    for index, evidence in enumerate(evidences, start=1):
        values = [
            str(evidence.get(key))
            for key in ("test_type", "item", "value", "conditions", "institute", "source_kind", "source_url")
            if evidence.get(key)
        ]
        evidence_rows.append(f"[E{index}] " + " / ".join(values))
    lines = [
        "[생성 요청]",
        instruction,
        "",
        "[제품]",
        f"- 제품명: {_display_name(product)}",
        f"- 구분: {product.get('category', '일반')}",
        f"- 심사(보고) 기능성: {product.get('functional_type') or '없음'}",
        f"- 주요 성분: {', '.join(product.get('key_ingredients') or []) or '없음'}",
        *product_fact_lines(product),
        f"- 사용자 제품 설명/콘셉트: {product_description or '없음'}",
        f"- 다듬을 이전 광고문: {reference_copy or '없음'}",
        "",
        "[광고 조건]",
        f"- 채널: {channel}",
        f"- 분위기: {tone}",
        f"- 길이: {length}",
        f"- 포함 키워드: {', '.join(keywords) if keywords else '없음'}",
        "",
        "[사용 가능한 보유 실증자료]",
        *(evidence_rows or ["- 없음"]),
        "",
        "[쓸 수 있는 표현 상한 - 코드가 보유 근거로 계산]",
        claim_menu or "- (계산된 상한 없음)",
        "",
        "[관련 규정]",
        evidence_text or "- 검색된 규정 없음",
        "",
        "[창작 구조 참고 - 브랜드 원문·효능·숫자 복사 금지]",
        creative_prompt(),
    ]
    # 시장·성분 역할 자료는 보통 [쓸 수 있는 재료] 안에 들어간다. 따로 넘어온 경우에만 섹션을 붙인다.
    if market_reference_text:
        lines += ["", "[시장 표현 참고 - 실증이나 규정 근거로 사용 금지]", market_reference_text]
    if ingredient_reference_text:
        lines += ["", "[성분 역할 참고 - 완제품 실증·법령 근거 아님]", ingredient_reference_text]
    if knowledge:
        lines += ["", "[쓸 수 있는 재료 - 우리가 모은 데이터를 제품 기준으로 연결]", knowledge]
    if retry_note:
        lines += ["", "[이전 후보 검증 실패]", retry_note, "위 문제를 모두 제거해 새 후보를 작성한다."]
    return "\n".join(lines)
